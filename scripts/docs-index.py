#!/usr/bin/env python3
"""Builds the website's documentation search index.

Reads every page under app/site/src/jsMain/resources/markdown/docs and writes DocsIndex.kt: one entry per ## and ###
heading with the page's route and the heading's anchor, which the site search (⌘K) offers as "Docs sections".
Anchors follow the markdown plugin's rule for heading ids: lowercase, punctuation dropped, spaces to hyphens.
"""
import glob
import os
import re
import sys


def anchor(text):
    text = text.replace('`', '').lower()
    text = re.sub(r'[^a-z0-9 -]', '', text)
    text = re.sub(r'\s+', '-', text.strip())
    return re.sub(r'-+', '-', text)


def kotlin(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def sections(path):
    with open(path, encoding='utf-8') as handle:
        lines = handle.read().split('\n')
    route, title, body = None, None, lines
    if lines and lines[0].strip() == '---':
        for index in range(1, len(lines)):
            if lines[index].strip() == '---':
                body = lines[index + 1:]
                break
            key, _, value = lines[index].partition(':')
            if key.strip() == 'routeOverride':
                route = value.strip()
            if key.strip() == 'title':
                title = value.strip()
    if not route:
        return []
    route = route.rstrip('/') or '/docs'
    found, fence = [], False
    for line in body:
        stripped = line.lstrip()
        if stripped.startswith('```') or stripped.startswith('~~~'):
            fence = not fence
            continue
        if fence:
            continue
        match = re.match(r'^(##|###) +(.+?)\s*#*\s*$', line)
        if not match:
            continue
        heading = match.group(2).replace('`', '').replace('\\<', '<').replace('\\>', '>').strip()
        found.append((route, title or route, heading, anchor(match.group(2)), len(match.group(1))))
    return found


def main(src, out):
    entries = []
    for path in sorted(glob.glob(os.path.join(src, '*.md'))):
        entries.extend(sections(path))
    with open(out, 'w', encoding='utf-8') as handle:
        handle.write('// Generated by scripts/docs-index.sh from resources/markdown/docs. Do not edit by hand.\n')
        handle.write('package org.example.app.components\n\n')
        handle.write('/** One section of the documentation: the page it is on and the anchor of its heading. */\n')
        handle.write('class DocSection(val route: String, val page: String, val heading: String, val anchor: String, val level: Int)\n\n')
        handle.write('/** Every ## and ### heading of the docs, for the site search. */\n')
        handle.write('val DocsIndex: List<DocSection> = listOf(\n')
        for route, title, heading, anc, level in entries:
            handle.write(f'    DocSection({kotlin(route)}, {kotlin(title)}, {kotlin(heading)}, {kotlin(anc)}, {level}),\n')
        handle.write(')\n')
    print(f'docs-index: {len(entries)} sections written to {out}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
